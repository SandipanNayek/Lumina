import pptxgen from "pptxgenjs"

const COLORS = {
    darkBg: "07090E",
    darkCard: "111827",
    lightBg: "F8FAFC",
    cardBg: "FFFFFF",
    cardBorder: "E2E8F0",
    teal: "0D9488",
    tealBright: "2DD4BF",
    textDark: "0F172A",
    textBody: "334155",
    textLight: "F8FAFC",
    textMuted: "94A3B8",
}

const FONT = "Arial"

export const generatePpt = async (data) => {
    const ppt = new pptxgen()

    ppt.layout = "LAYOUT_WIDE" // 13.33" x 7.5" (16:9 Widescreen)
    ppt.author = "Lumina"
    ppt.company = "Lumina"
    ppt.title = data.title || "Generated Presentation"

    const sections = data.sections || []
    const totalSlides = sections.length + 2

    // ==========================================
    // 1. COVER SLIDE (Dark Lumina Theme)
    // ==========================================
    const coverSlide = ppt.addSlide()
    coverSlide.background = { color: COLORS.darkBg }

    // Left vertical accent bar
    coverSlide.addShape(ppt.ShapeType.rect, {
        x: 0.85,
        y: 1.75,
        w: 0.08,
        h: 3.7,
        fill: { color: COLORS.tealBright },
    })

    // Eyebrow tag
    coverSlide.addText("GENERATED BY LUMINA", {
        x: 1.15,
        y: 1.75,
        w: 10.5,
        h: 0.35,
        fontFace: FONT,
        fontSize: 11,
        bold: true,
        color: COLORS.tealBright,
        charSpacing: 3,
    })

    // Main Presentation Title
    coverSlide.addText(data.title || "Generated Presentation", {
        x: 1.15,
        y: 2.2,
        w: 11.2,
        h: 1.85,
        fontFace: FONT,
        fontSize: 38,
        bold: true,
        color: COLORS.textLight,
        valign: "top",
        breakLine: true,
    })

    // Subtitle
    if (data.subtitle) {
        coverSlide.addText(data.subtitle, {
            x: 1.15,
            y: 4.2,
            w: 10.5,
            h: 1.25,
            fontFace: FONT,
            fontSize: 17,
            color: COLORS.textMuted,
            valign: "top",
        })
    }

    // Cover Footer
    coverSlide.addText(`1 / ${totalSlides}`, {
        x: 11.2,
        y: 6.9,
        w: 1.3,
        h: 0.3,
        fontFace: FONT,
        fontSize: 10,
        color: COLORS.textMuted,
        align: "right",
    })

    // ==========================================
    // 2. CONTENT SLIDES (1 per Section)
    // ==========================================
    sections.forEach((section, index) => {
        const slide = ppt.addSlide()
        slide.background = { color: COLORS.lightBg }

        // Top section badge
        slide.addText(`SECTION ${String(index + 1).padStart(2, "0")}`, {
            x: 0.85,
            y: 0.55,
            w: 4.0,
            h: 0.3,
            fontFace: FONT,
            fontSize: 10,
            bold: true,
            color: COLORS.teal,
            charSpacing: 2,
        })

        // Section Heading
        slide.addText(section.heading || `Section ${index + 1}`, {
            x: 0.85,
            y: 0.88,
            w: 11.6,
            h: 0.75,
            fontFace: FONT,
            fontSize: 26,
            bold: true,
            color: COLORS.textDark,
        })

        // Divider Line
        slide.addShape(ppt.ShapeType.line, {
            x: 0.85,
            y: 1.72,
            w: 11.63,
            h: 0,
            line: { color: COLORS.cardBorder, width: 1.2 },
        })

        const points = section.points || []
        const useTwoColumns = points.length > 4

        if (!useTwoColumns) {
            // Single-column clean cards (1 to 4 points)
            const cardHeight = 0.98
            const gap = 0.2
            const startY = 2.0

            points.forEach((point, pIdx) => {
                const y = startY + pIdx * (cardHeight + gap)

                // Card container
                slide.addShape(ppt.ShapeType.roundRect, {
                    x: 0.85,
                    y,
                    w: 11.63,
                    h: cardHeight,
                    rectRadius: 0.08,
                    fill: { color: COLORS.cardBg },
                    line: { color: COLORS.cardBorder, width: 1 },
                })

                // Number pill
                slide.addShape(ppt.ShapeType.roundRect, {
                    x: 1.08,
                    y: y + 0.24,
                    w: 0.5,
                    h: 0.5,
                    rectRadius: 0.08,
                    fill: { color: COLORS.teal },
                })

                slide.addText(String(pIdx + 1).padStart(2, "0"), {
                    x: 1.08,
                    y: y + 0.24,
                    w: 0.5,
                    h: 0.5,
                    fontFace: FONT,
                    fontSize: 13,
                    bold: true,
                    color: COLORS.textLight,
                    align: "center",
                    valign: "middle",
                })

                // Point text
                slide.addText(point, {
                    x: 1.78,
                    y: y + 0.1,
                    w: 10.45,
                    h: cardHeight - 0.2,
                    fontFace: FONT,
                    fontSize: 15,
                    color: COLORS.textBody,
                    valign: "middle",
                })
            })
        } else {
            // 2-Column grid cards (5 to 6+ points)
            const colWidth = 5.65
            const cardHeight = 1.32
            const colGap = 0.33
            const rowGap = 0.22
            const startY = 2.0

            points.slice(0, 6).forEach((point, pIdx) => {
                const col = pIdx % 2
                const row = Math.floor(pIdx / 2)
                const x = 0.85 + col * (colWidth + colGap)
                const y = startY + row * (cardHeight + rowGap)

                slide.addShape(ppt.ShapeType.roundRect, {
                    x,
                    y,
                    w: colWidth,
                    h: cardHeight,
                    rectRadius: 0.08,
                    fill: { color: COLORS.cardBg },
                    line: { color: COLORS.cardBorder, width: 1 },
                })

                // Top accent strip on card
                slide.addShape(ppt.ShapeType.rect, {
                    x: x + 0.22,
                    y: y + 0.18,
                    w: 0.42,
                    h: 0.05,
                    fill: { color: COLORS.teal },
                })

                slide.addText(point, {
                    x: x + 0.22,
                    y: y + 0.3,
                    w: colWidth - 0.44,
                    h: cardHeight - 0.4,
                    fontFace: FONT,
                    fontSize: 14,
                    color: COLORS.textBody,
                    valign: "top",
                })
            })
        }

        // Slide Footer
        slide.addText("Generated by Lumina", {
            x: 0.85,
            y: 6.95,
            w: 4.0,
            h: 0.3,
            fontFace: FONT,
            fontSize: 9.5,
            color: COLORS.textMuted,
        })

        slide.addText(`${index + 2} / ${totalSlides}`, {
            x: 11.2,
            y: 6.95,
            w: 1.28,
            h: 0.3,
            fontFace: FONT,
            fontSize: 9.5,
            color: COLORS.textMuted,
            align: "right",
        })
    })

    // ==========================================
    // 3. CLOSING SLIDE
    // ==========================================
    const endSlide = ppt.addSlide()
    endSlide.background = { color: COLORS.darkBg }

    endSlide.addShape(ppt.ShapeType.rect, {
        x: 6.16,
        y: 2.55,
        w: 1.0,
        h: 0.06,
        fill: { color: COLORS.tealBright },
    })

    endSlide.addText("Thank You", {
        x: 1.0,
        y: 2.8,
        w: 11.33,
        h: 1.0,
        fontFace: FONT,
        fontSize: 40,
        bold: true,
        color: COLORS.textLight,
        align: "center",
    })

    endSlide.addText("Generated by Lumina", {
        x: 1.0,
        y: 3.9,
        w: 11.33,
        h: 0.5,
        fontFace: FONT,
        fontSize: 15,
        color: COLORS.tealBright,
        align: "center",
    })

    endSlide.addText(`${totalSlides} / ${totalSlides}`, {
        x: 11.2,
        y: 6.9,
        w: 1.3,
        h: 0.3,
        fontFace: FONT,
        fontSize: 10,
        color: COLORS.textMuted,
        align: "right",
    })

    return await ppt.write({ outputType: "nodebuffer" })
}