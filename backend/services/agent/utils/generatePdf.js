import PDFDocument from "pdfkit"

export const generatePdf = async (data) => {
    return new Promise((resolve, reject) => {
        const doc = new PDFDocument({
            size: "A4",
            margins: { top: 50, bottom: 60, left: 50, right: 50 },
            bufferPages: true,
            info: {
                Author: "Lumina",
                Title: data.title || "Generated Document",
                Creator: "Lumina"
            }
        })

        const chunks = []

        doc.on("data", (chunk) => chunks.push(chunk))
        doc.on("end", () => resolve(Buffer.concat(chunks)))
        doc.on("error", reject)

        doc.font("Helvetica-Bold")
            .fontSize(28)
            .fillColor("#000000")
            .text(data.title || "Generated Document", { align: "left" })

        if (data.subtitle) {
            doc.moveDown(0.4)
                .font("Helvetica")
                .fontSize(14)
                .fillColor("#475569")
                .text(data.subtitle)
        }

        doc.moveDown(1)
            .moveTo(50, doc.y)
            .lineTo(545, doc.y)
            .strokeColor("#cbd5e1")
            .stroke()
        doc.moveDown(1)

        const sections = data.sections || []
        sections.forEach((section, idx) => {
            doc.font("Helvetica-Bold")
                .fontSize(16)
                .fillColor("#0d9488")
                .text(section.heading || "")

            doc.moveDown(0.4)

            for (const point of section.points || []) {
                doc.font("Helvetica")
                    .fontSize(12.5)
                    .fillColor("#1e293b")
                    .text(`•  ${point}`, {
                        indent: 12,
                        lineGap: 4,
                    })
                doc.moveDown(0.3)
            }

            if (idx < sections.length - 1) {
                doc.moveDown(0.9)
            }
        })

        const range = doc.bufferedPageRange()
        for (let i = range.start; i < range.start + range.count; i++) {
            doc.switchToPage(i)

            const prevBottom = doc.page.margins.bottom
            doc.page.margins.bottom = 0

            const footerY = doc.page.height - 38

            doc.moveTo(50, footerY - 8)
                .lineTo(545, footerY - 8)
                .strokeColor("#e2e8f0")
                .lineWidth(0.5)
                .stroke()

            doc.font("Helvetica")
                .fontSize(9.5)
                .fillColor("#94a3b8")
                .text("Generated by Lumina", 50, footerY, {
                    width: 495,
                    align: "left",
                    lineBreak: false,
                })

            doc.text(`Page ${i + 1} of ${range.count}`, 50, footerY, {
                width: 495,
                align: "right",
                lineBreak: false,
            })

            doc.page.margins.bottom = prevBottom
        }

        doc.end()
    })
}